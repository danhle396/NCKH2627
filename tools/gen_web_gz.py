#!/usr/bin/env python
# tools/gen_web_gz.py — trang web của bản dự thi (fw_arm/src/core/trang_web_html.h, chuỗi R"HTML(...)HTML" của ESP32)
# → bản nén gzip cho flash M3 (kế hoạch 7.3: trình duyệt tự giải nén). Đổi vài chữ cho thiết bị mới, kiểm từng chỗ đổi.
#   python -I tools/gen_web_gz.py  → fw_arm/src/gen/trang_web_gz.h, trang_web_gz.c
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "fw_arm/src/core/trang_web_html.h"
OUT = ROOT / "fw_arm/src/gen"
REPL = [                                              # (cũ, mới, số chỗ phải có)
    ("Thiết bị đeo ngực", "Thiết bị đeo bắp tay", None),
    ("'lỗi SPI rc='", "'lỗi bộ tăng tốc rc='", 1),
    ("'SPI '+d.s.spi_khz+' kHz'", "'bước '+d.s.cyc+' chu kỳ'", 1),
]


def main():
    sys.stdout.reconfigure(encoding="utf8")
    s = SRC.read_text(encoding="utf8")
    m = re.search(r'R"HTML\((.*)\)HTML"', s, re.S)
    html = m.group(1)
    for a, b, n in REPL:
        k = html.count(a)
        assert k >= 1 and (n is None or k == n), f"'{a}' xuất hiện {k} lần"
        html = html.replace(a, b)
    raw = html.encode("utf8")
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "trang_web_gz.h").write_text(
        "/* GENERATED by tools/gen_web_gz.py - DO NOT EDIT. Trang web nén gzip (Content-Encoding: gzip). */\n"
        "#ifndef TRANG_WEB_GZ_H\n#define TRANG_WEB_GZ_H\n#include <stdint.h>\n"
        f"#define TRANG_WEB_GZ_LEN {len(gz)}u\nextern const uint8_t trang_web_gz[TRANG_WEB_GZ_LEN];\n#endif\n",
        encoding="utf8", newline="\n")
    lines = ["/* GENERATED by tools/gen_web_gz.py - DO NOT EDIT. */", '#include "trang_web_gz.h"',
             "const uint8_t trang_web_gz[TRANG_WEB_GZ_LEN] = {"]
    for i in range(0, len(gz), 20):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in gz[i:i + 20]) + ",")
    lines.append("};")
    (OUT / "trang_web_gz.c").write_text("\n".join(lines) + "\n", encoding="utf8", newline="\n")
    assert gzip.decompress(gz) == raw
    print(f"trang web: {len(raw)} B → gzip {len(gz)} B; giải nén lại trùng từng byte")


if __name__ == "__main__":
    main()
